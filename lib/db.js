/* ------------------------------ adapter SQLite ------------------------------ */

function sqliteAdapter(file) {
  const { DatabaseSync } = require('node:sqlite');
  const raw = new DatabaseSync(file);
  raw.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON; PRAGMA busy_timeout = 5000;');
  const norm = (p) => p.map((v) => (v === undefined ? null : v));
  const ops = {
    async get(sql, ...p) {
      return raw.prepare(sql).get(...norm(p));
    },
    async all(sql, ...p) {
      return raw.prepare(sql).all(...norm(p));
    },
    async run(sql, ...p) {
      const r = raw.prepare(sql).run(...norm(p));
      return { changes: Number(r.changes) };
    },
    async exec(sql) {
      raw.exec(sql);
    },
  };
  // Una sola connessione: le transazioni vengono messe in coda una alla volta.
  let chain = Promise.resolve();
  return {
    kind: 'sqlite',
    ...ops,
    tx(fn) {
      const job = chain.then(async () => {
        raw.exec('BEGIN IMMEDIATE');
        const t = { ...ops, tx: (f) => f(t) };
        try {
          const out = await fn(t);
          raw.exec('COMMIT');
          return out;
        } catch (e) {
          raw.exec('ROLLBACK');
          throw e;
        }
      });
      chain = job.catch(() => {});
      return job;
    },
    async close() {
      await chain;
      raw.close();
    },
  };
}

/* ------------------------------ adapter Postgres ------------------------------ */

const toPgSql = (sql) => {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
};

function pgAdapter(url, pgModule) {
  const pg = pgModule || require('pg'); // caricato solo in produzione
  // BIGINT / COUNT(*) tornano come stringhe: li vogliamo numeri
  pg.types.setTypeParser(20, (v) => Number(v));
  const pool = new pg.Pool({
    connectionString: url,
    // serverless: poche connessioni per istanza, rilasciate presto
    max: process.env.VERCEL ? 1 : 5,
    idleTimeoutMillis: 10_000,
    connectionTimeoutMillis: 15_000,
  });
  pool.on('error', (e) => console.error('[pg] errore sul pool:', e.message));

  const make = (q) => ({
    async get(sql, ...p) {
      return (await q.query(toPgSql(sql), p)).rows[0];
    },
    async all(sql, ...p) {
      return (await q.query(toPgSql(sql), p)).rows;
    },
    async run(sql, ...p) {
      return { changes: (await q.query(toPgSql(sql), p)).rowCount };
    },
    async exec(sql) {
      await q.query(sql);
    },
  });

  return {
    kind: 'pg',
    ...make(pool),
    async tx(fn) {
      const client = await pool.connect();
      const t = { ...make(client), tx: (f) => f(t) };
      try {
        await client.query('BEGIN');
        const out = await fn(t);
        await client.query('COMMIT');
        return out;
      } catch (e) {
        try {
          await client.query('ROLLBACK');
        } catch {
          /* connessione già persa */
        }
        throw e;
      } finally {
        client.release();
      }
    },
    async close() {
      await pool.end();
    },
  };
}

/* ------------------------------ apertura e seed ------------------------------ */

async function openDb(cfg, overrides = {}) {
  let db;
  if (cfg.databaseUrl) {
    db = pgAdapter(cfg.databaseUrl, overrides.pg);
  } else {
    fs.mkdirSync(cfg.dataDir, { recursive: true });
    db = sqliteAdapter(path.join(cfg.dataDir, 'shop.db'));
  }
  await ensureSchema(db);
  return db;
}

async function ensureSchema(db) {
  let ready = false;
  try {
    ready = Boolean(await db.get("SELECT value FROM settings WHERE key = 'schema_version'"));
  } catch {
    ready = false; // tabella inesistente: primo avvio
  }
  if (ready) return;

  await db.exec(schema(db.kind === 'pg'));
  // Chi inserisce per primo il marcatore esegue il seed (sicuro con avvii concorrenti)
  const r = await db.run("INSERT INTO settings (key, value) VALUES ('schema_version', '1') ON CONFLICT (key) DO NOTHING");
  if (r.changes !== 1) return;

  for (const [k, v] of Object.entries(DEFAULT_SETTINGS)) {
    await db.run('INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT (key) DO NOTHING', k, v);
  }
  const { n } = await db.get('SELECT COUNT(*) AS n FROM products');
  if (n === 0) {
    for (const p of SEED_PRODUCTS) {
      const row = await db.get(
        'INSERT INTO products (title, category, price_cents, stock, image, description, created_at) VALUES (?, ?, ?, ?, ?, ?, ?) RETURNING id',
        p.title, p.category, p.price_cents, p.stock, p.image, p.description, tsNow()
      );
      await db.run('INSERT INTO coupons (code, percent, product_id) VALUES (?, ?, ?)', p.coupon.code, p.coupon.percent, row.id);
    }
    await db.run('INSERT INTO coupons (code, percent, product_id) VALUES (?, ?, NULL)', 'NATALE15', 15);
  }
}

async function getSettings(db) {
  const out = { ...DEFAULT_SETTINGS };
  for (const r of await db.all('SELECT key, value FROM settings')) out[r.key] = r.value;
  return out;
}

async function setSetting(db, key, value) {
  await db.run(
    'INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT (key) DO UPDATE SET value = excluded.value',
    key,
    String(value)
  );
}

